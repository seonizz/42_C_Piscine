#include <unistd.h>

void	ft_print_comb(void)
{
	char	i;
	char	j;
	char	k;

	i = '0';
	while (i <= 55)
	{
		j = i + 1;
		while (j <= 56)
		{
			k = j + 1;
			while (k <= 57)
			{
				write (1, &i, 1);
				write (1, &j, 1);
				write (1, &k, 1);
				k++;
				if (i != 55 || j != 56 || k != 57)
					write (1, ", ", 2);
			}
			j++;
		}
		i++;
	}
}
