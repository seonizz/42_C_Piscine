#include <unistd.h>

void	ft_putnbr(int nb)
{
	char	i;
	long	a;

	a = nb;
	if (a < 0)
	{
		write(1, "-", 1);
		a = -a;
	}
	if (a < 10)
	{
		i = '0' + (a % 10);
		write(1, &i, 1);
		return ;
	}
	if (a >= 10)
		ft_putnbr(a / 10);
	i = '0' + (a % 10);
	write(1, &i, 1);
}
